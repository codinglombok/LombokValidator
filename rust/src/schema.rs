//! Trait-based custom validators and schema-level (struct, nested object)
//! composition.
//!
//! A real `#[derive(LombokValidate)]` proc-macro (per the original master
//! prompt) needs a `proc-macro2`/`syn`/`quote` dependency chain that
//! conflicts with the zero-dep-runtime rule for the *runtime* crate —
//! ecosystem convention (see LombokSerde) is to ship the macro in a
//! separate `lombokvalidator-derive` crate that only the *build*
//! depends on. That crate isn't built in this pass; `Schema` below is the
//! hand-written equivalent of what the derive macro would generate, and
//! is what a generated `impl Validate for T` would call into.

use crate::error::{merge_results, ValidationResult};
use alloc::boxed::Box;
use alloc::string::{String, ToString};
use alloc::vec::Vec;

/// Implemented by anything LombokValidator can validate as a whole —
/// hand-written today, generated by `#[derive(LombokValidate)]` later.
pub trait Validate {
    fn validate(&self) -> ValidationResult;
}

/// A single named field rule: given the field's value, return Ok or a
/// list of errors. Boxed so `Schema` can hold a heterogeneous set of
/// rules across different field types via type-erased closures.
type Rule<'a> = Box<dyn Fn() -> ValidationResult + 'a>;

/// Struct-level validator built from named rules, run against every
/// field and merged into a single result — this is the non-macro
/// equivalent of `#[derive(LombokValidate)]` on a struct.
#[derive(Default)]
pub struct Schema<'a> {
    rules: Vec<(String, Rule<'a>)>,
}

impl<'a> Schema<'a> {
    pub fn new() -> Self {
        Schema { rules: Vec::new() }
    }

    /// Register a rule for `field`. `check` is any zero-argument closure
    /// returning a [`ValidationResult`] — typically a call into
    /// `string::validate_*` / `number::validate_*` with the field's
    /// current value captured.
    pub fn field(
        mut self,
        field: impl Into<String>,
        check: impl Fn() -> ValidationResult + 'a,
    ) -> Self {
        self.rules.push((field.into(), Box::new(check)));
        self
    }

    /// Nest another object's [`Validate`] impl under `field`, prefixing
    /// its errors' field names with `"<field>."` for nested-object
    /// reporting (scope item 3: "Schema validation (struct-level, nested
    /// objects)").
    pub fn nested(
        mut self,
        field: impl Into<String> + Clone + 'a,
        child: &'a dyn Validate,
    ) -> Self {
        let prefix = field.into();
        self.rules.push((
            prefix.clone(),
            Box::new(move || {
                child.validate().map_err(|errs| {
                    errs.into_iter()
                        .map(|mut e| {
                            e.field = alloc::format!("{}.{}", prefix, e.field);
                            e
                        })
                        .collect()
                })
            }),
        ));
        self
    }

    pub fn validate_all(&self) -> ValidationResult {
        let results: Vec<ValidationResult> = self.rules.iter().map(|(_, r)| r()).collect();
        merge_results(results)
    }
}

/// A minimal reusable "custom validator" trait for one value type, per
/// scope item 4 ("Custom validators (trait-based)"). Implement this for
/// domain rules that don't fit the built-in string/number validators.
pub trait FieldValidator<T> {
    fn check(&self, field: &str, value: &T) -> ValidationResult;
}

/// Adapts a plain closure into a [`FieldValidator`], so ad-hoc rules
/// don't need a named type.
pub struct ClosureValidator<F>(pub F);

impl<T, F> FieldValidator<T> for ClosureValidator<F>
where
    F: Fn(&str, &T) -> ValidationResult,
{
    fn check(&self, field: &str, value: &T) -> ValidationResult {
        (self.0)(field, value)
    }
}

#[allow(dead_code)]
fn _keep_to_string(s: &str) -> String {
    s.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::ValidationError;
    use crate::number::validate_range_i64;
    use crate::string::validate_email;

    struct SignupForm {
        email: &'static str,
        age: i64,
    }

    impl Validate for SignupForm {
        fn validate(&self) -> ValidationResult {
            Schema::new()
                .field("email", || validate_email("email", self.email))
                .field("age", || {
                    validate_range_i64("age", self.age, Some(13), Some(120))
                })
                .validate_all()
        }
    }

    #[test]
    fn schema_collects_multiple_errors() {
        let form = SignupForm {
            email: "not-an-email",
            age: 5,
        };
        let errs = form.validate().unwrap_err();
        assert_eq!(errs.len(), 2);
        assert!(errs.iter().any(|e| e.field == "email"));
        assert!(errs.iter().any(|e| e.field == "age"));
    }

    #[test]
    fn schema_passes_when_all_rules_pass() {
        let form = SignupForm {
            email: "user@example.com",
            age: 25,
        };
        assert!(form.validate().is_ok());
    }

    struct Address {
        postcode: &'static str,
    }
    impl Validate for Address {
        fn validate(&self) -> ValidationResult {
            Schema::new()
                .field("postcode", || {
                    crate::string::validate_length("postcode", self.postcode, Some(5), Some(5))
                })
                .validate_all()
        }
    }

    struct Order {
        address: Address,
    }
    impl Validate for Order {
        fn validate(&self) -> ValidationResult {
            Schema::new()
                .nested("address", &self.address)
                .validate_all()
        }
    }

    #[test]
    fn nested_object_prefixes_field_name() {
        let order = Order {
            address: Address { postcode: "12" },
        };
        let errs = order.validate().unwrap_err();
        assert_eq!(errs[0].field, "address.postcode");
    }

    #[test]
    fn custom_closure_validator() {
        let is_even = ClosureValidator(|field: &str, value: &i64| {
            if value % 2 == 0 {
                Ok(())
            } else {
                Err(alloc::vec![ValidationError::new(
                    field,
                    "NOT_EVEN",
                    "validator.custom.not_even"
                )])
            }
        });
        assert!(is_even.check("count", &4).is_ok());
        assert!(is_even.check("count", &3).is_err());
    }
}
